/**
 * Hàm hỗ trợ dịch thuật tự động cho bản đồ
 */
window.MAP_I18N = {
  data: MAP_TRANSLATIONS,

  /**
   * Dịch một tên hoặc cụm từ bất kỳ
   */
  t(rawText, fallback = "") {
    if (!rawText) return fallback || "";
    const str = String(rawText).trim();

    // 1. Kiểm tra đối chiếu trực tiếp từ điển terms
    if (MAP_TRANSLATIONS.terms[str]) return MAP_TRANSLATIONS.terms[str];
    if (MAP_TRANSLATIONS.groups[str]) return MAP_TRANSLATIONS.groups[str];

    // 2. Kiểm tra bản đồ
    if (MAP_TRANSLATIONS.maps[str]) return MAP_TRANSLATIONS.maps[str];

    // 3. Kiểm tra cấp độ
    if (MAP_TRANSLATIONS.levels[str]) return MAP_TRANSLATIONS.levels[str];

    // 4. Kiểm tra điều kiện
    if (MAP_TRANSLATIONS.conditions[str]) return MAP_TRANSLATIONS.conditions[str];

    // 5. Kiểm tra tầng
    if (MAP_TRANSLATIONS.floors[str]) return MAP_TRANSLATIONS.floors[str];

    // 6. Kiểm tra khu vực
    if (MAP_TRANSLATIONS.regions && MAP_TRANSLATIONS.regions[str]) return MAP_TRANSLATIONS.regions[str];

    // 7. Kiểm tra thay thế từng phần (nếu chuỗi ghép)
    for (const [key, val] of Object.entries(MAP_TRANSLATIONS.terms)) {
      if (str.includes(key)) {
        return str.replace(new RegExp(key, "g"), val);
      }
    }

    return fallback || str;
  },

  /**
   * Dịch điều kiện mở khóa / nhặt đồ / xuất hiện
   */
  tCondition(cond) {
    if (!cond) return "";
    const trimmed = String(cond).trim();
    if (MAP_TRANSLATIONS.conditions[trimmed]) return MAP_TRANSLATIONS.conditions[trimmed];
    return window.MAP_I18N ? window.MAP_I18N.t(trimmed, trimmed) : trimmed;
  },

  /**
   * Định dạng nhãn tầng (vd: "Thường · Tầng 1", "Mật · Tầng Hầm B1")
   */
  tFloor(item) {
    if (!item) return "";
    const level = this.t(item.level || "Thường");
    const suffix = item.id ? item.id.match(/_(B1|[0-4]F)$/i)?.[1] : null;
    if (suffix) {
      const floorName = MAP_TRANSLATIONS.floors[suffix.toUpperCase()] || `Tầng ${suffix}`;
      return `${level} · ${floorName}`;
    }
    return level;
  }
};
